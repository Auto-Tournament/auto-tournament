/** Wraps a timer body so a tick that finds the previous one still running is skipped. */
export function guarded(fn: () => Promise<void>): () => Promise<void> {
  let running = false;
  return async () => {
    if (running) return;
    running = true;
    try {
      await fn();
    } finally {
      running = false;
    }
  };
}
